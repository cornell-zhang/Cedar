"""DC -> Innovus -> gate-level activity simulation -> PrimeTime, and Conformal.

Adapters generate tool scripts from the technology profile and design spec.
One generated SDC (library time units) is used by every stage so the baseline
and every candidate are measured under identical constraints. Site-specific
behaviour is added through the documented Tcl hooks in the technology profile.

Measurement convention (``full-ppa``, matching the paper's setup):

* area  — DC post-synthesis total cell area (um2)
* delay — DC post-synthesis critical-path data arrival time (ns)
* slack / timing_met — DC post-synthesis worst slack against the declared clock
* power — PrimeTime averaged total power on the post-route netlist with SPEF
  parasitics and SAIF activity from SDF-annotated gate-level simulation (uW)
"""

from __future__ import annotations

import glob
import re
import shutil
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Sequence

from ..config import Loaded
from ..metrics import Metric
from .runner import StageResult, ToolEnv

_SV_HINTS = re.compile(r"\b(always_comb|always_ff|always_latch|logic|typedef|struct|enum|interface|package|import|unique\s+case|priority\s+case)\b")


def detect_hdl(files: Sequence[str]) -> str:
    for f in files:
        if f.endswith((".sv", ".svh")):
            return "sverilog"
        try:
            if _SV_HINTS.search(Path(f).read_text(errors="replace")):
                return "sverilog"
        except OSError:
            pass
    return "verilog"


def _expand(items: Sequence[dict]) -> List[str]:
    out: List[str] = []
    for it in items or []:
        if not it:
            continue
        if it.get("matches") is not None:
            out += it["matches"]
        elif any(ch in it["path"] for ch in "*?["):
            out += sorted(glob.glob(it["path"]))
        else:
            out.append(it["path"])
    return out


def tcl_list(items: Sequence[str]) -> str:
    return "[list " + " ".join("{" + s + "}" for s in items) + "]"


@dataclass
class FlowContext:
    tools: ToolEnv
    tech: Loaded
    corner: str
    top: str
    clocks: List[dict]
    io_delay_fraction: float
    sdc_path: Optional[str] = None          # user SDC (advanced)
    defines: Dict[str, str] = field(default_factory=dict)
    include_dirs: List[str] = field(default_factory=list)

    @property
    def time_unit(self) -> str:
        return self.tech.data["units"]["time"]

    def to_lib_time(self, ns: float) -> float:
        return ns * 1000.0 if self.time_unit == "ps" else ns

    def corner_data(self) -> dict:
        return self.tech.data["corners"][self.corner]

    def dbs(self) -> List[str]:
        return _expand(self.corner_data()["db"])

    def libs(self) -> List[str]:
        return _expand(self.corner_data()["liberty"])

    def sim_models(self) -> List[str]:
        return _expand(self.corner_data()["sim_models"])

    def rc_tech(self) -> str:
        return self.corner_data()["rc_tech"]["path"]

    def lefs(self) -> List[str]:
        lef = self.tech.data["lef"]
        return [lef["tech"]["path"]] + _expand(lef["cells"])

    def hook(self, section: str, key: str) -> Optional[str]:
        sec = self.tech.data.get(section) or {}
        h = sec.get(key)
        return h["path"] if h else None

    def write_sdc(self, path: Path) -> Path:
        """Generate the shared SDC (or copy the user SDC verbatim)."""
        if self.sdc_path:
            shutil.copy(self.sdc_path, path)
            return path
        c = self.clocks[0]
        period = self.to_lib_time(c["period_ns_resolved"])
        io = period * self.io_delay_fraction
        name = c.get("name") or "clk"
        lines = [f"# Generated by Cedar. Time unit: {self.time_unit}. Clock period {c['period_ns_resolved']} ns."]
        if c.get("port"):
            lines.append(f"create_clock -name {name} -period {period:.6g} [get_ports {{{c['port']}}}]")
        else:
            lines.append(f"create_clock -name {name} -period {period:.6g}")
        lines.append(f"set_input_delay {io:.6g} -clock {name} [all_inputs]")
        lines.append(f"set_output_delay {io:.6g} -clock {name} [all_outputs]")
        path.write_text("\n".join(lines) + "\n")
        return path


def _lib_or_default(ctx: "FlowContext", value: Optional[float], default_ns: float) -> float:
    """Explicit value (library time unit) or a default given in ns, converted."""
    return float(value) if value is not None else ctx.to_lib_time(default_ns)


# ---------------------------------------------------------------- parsers

def parse_dc_area(rpt: Path) -> Optional[float]:
    if not rpt.is_file():
        return None
    m = re.search(r"Total cell area:\s+([0-9.eE+-]+)", rpt.read_text(errors="replace"))
    return float(m.group(1)) if m else None


def parse_timing(rpt: Path) -> Dict[str, Optional[float]]:
    """First path of a DC/PT/Innovus style report: arrival and slack."""
    out: Dict[str, Optional[float]] = {"arrival": None, "slack": None, "met": None}
    if not rpt.is_file():
        return out
    txt = rpt.read_text(errors="replace")
    m = re.search(r"data arrival time\s+(-?[0-9.eE+-]+)", txt)
    if m:
        out["arrival"] = abs(float(m.group(1)))
    s = re.search(r"slack \((MET|VIOLATED)[^)]*\)\s+(-?[0-9.eE+-]+)", txt)
    if s:
        out["slack"] = float(s.group(2))
        out["met"] = s.group(1) == "MET"
    else:
        s2 = re.search(r"Slack Time\s+(-?[0-9.eE+-]+)", txt)    # Innovus report_timing
        if s2:
            out["slack"] = float(s2.group(1))
            out["met"] = out["slack"] >= 0
    return out


def parse_pt_power(rpt: Path) -> Optional[float]:
    """PrimeTime ``report_power`` total, returned in W (PT reports W by default)."""
    if not rpt.is_file():
        return None
    txt = rpt.read_text(errors="replace")
    m = re.search(r"^\s*Total Power\s*=\s*([0-9.eE+-]+)\s*(W|mW|uW|nW|pW)?", txt, re.M)
    if not m:
        return None
    unit = m.group(2) or "W"
    return float(m.group(1)) * {"W": 1.0, "mW": 1e-3, "uW": 1e-6, "nW": 1e-9, "pW": 1e-12}[unit]


def parse_saif_coverage(pt_log: Path) -> Optional[float]:
    """Percent of nets annotated from SAIF, from PrimeTime's read_saif summary."""
    if not pt_log.is_file():
        return None
    m = re.search(r"Number of annotated nets\s*=\s*\d+\s*\(\s*([0-9.]+)%\)", pt_log.read_text(errors="replace"))
    return float(m.group(1)) if m else None


# ---------------------------------------------------------------- stages

def synthesize(ctx: FlowContext, rtl: Sequence[str], work: Path, timeout: Optional[int] = None) -> StageResult:
    work.mkdir(parents=True, exist_ok=True)
    res = work / "results"
    res.mkdir(exist_ok=True)
    sdc = ctx.write_sdc(work / "constraints.sdc")
    syn = ctx.tech.data.get("synthesis") or {}
    period = ctx.to_lib_time(ctx.clocks[0]["period_ns_resolved"])
    hdl = detect_hdl(rtl)
    defines = " ".join(f"{k}={v}" if v not in (None, "") else k for k, v in ctx.defines.items())
    lines = [
        "set hdlin_enable_rtlinfo true",
        "set verilogout_show_unconnected_pins true",
        f"set_host_options -max_cores {ctx.tools.threads}",
        f"set dbs {tcl_list(ctx.dbs())}",
        "set_app_var target_library $dbs",
        "set_app_var link_library [concat * $dbs]",
        "set_app_var synthetic_library $dbs",
        "set_dp_smartgen_options -all_options false",
        "set compile_dp_optimization false",
        f"set_app_var search_path [concat [get_app_var search_path] {tcl_list(ctx.include_dirs)}]",
        "define_design_lib WORK -path ./WORK",
        f"if {{[catch {{analyze -format {hdl} {('-define {' + defines + '} ') if defines else ''}{tcl_list(list(rtl))}}} e]}} {{ puts \"CEDAR_ERROR analyze: $e\"; exit 2 }}",
        f"if {{![elaborate {ctx.top}]}} {{ puts \"CEDAR_ERROR elaborate failed\"; exit 2 }}",
        f"current_design {ctx.top}",
        "if {![link]} { puts \"CEDAR_ERROR link failed\"; exit 2 }",
        f"source {{{sdc}}}",
        f"set_max_fanout {syn.get('max_fanout', 16)} [current_design]",
        f"set_max_transition {_lib_or_default(ctx, syn.get('max_transition'), 0.050):.6g} [all_outputs]",
        f"set_input_transition -max {_lib_or_default(ctx, syn.get('input_transition_max'), 0.060):.6g} [all_inputs]",
        f"set_input_transition -min {_lib_or_default(ctx, syn.get('input_transition_min'), 0.020):.6g} [all_inputs]",
    ]
    for cell in syn.get("dont_use") or []:
        lines.append(f"set_dont_use [get_lib_cells {cell}]")
    if ctx.hook("synthesis", "pre_compile_hook"):
        lines.append(f"source {{{ctx.hook('synthesis', 'pre_compile_hook')}}}")
    lines += [
        "set_fix_multiple_port_nets -all -buffer_constants -feedthroughs [all_designs]",
        "check_design -summary",
        syn.get("compile_command") or "compile -map_effort high -area_effort high -no_design_rule -power_effort high",
    ]
    if ctx.hook("synthesis", "post_compile_hook"):
        lines.append(f"source {{{ctx.hook('synthesis', 'post_compile_hook')}}}")
    lines += [
        "ungroup -all -flatten",
        "set unmapped [sizeof_collection [get_cells -hier -filter \"is_unmapped == true\" -quiet]]",
        "if {$unmapped > 0} { puts \"CEDAR_ERROR $unmapped unmapped cells after compile\"; exit 3 }",
        "change_names -rules verilog -hierarchy",
        f"write -format verilog -hierarchy -output {{{res}/netlist.v}}",
        f"write_sdc -nosplit {{{res}/mapped.sdc}}",
        f"report_cross_probing -nosplit [get_cells -hierarchical] > {{{res}/cross_probing.rpt}}",
        f"report_qor > {{{res}/qor.rpt}}",
        f"report_timing -nosplit -max_paths 1 > {{{res}/timing.rpt}}",
        f"report_timing -nosplit -path full -max_paths 1 -nets > {{{res}/critical_path.rpt}}",
        f"report_area -nosplit > {{{res}/area.rpt}}",
        f"report_power -nosplit > {{{res}/power.rpt}}",
        f"report_reference -nosplit > {{{res}/ref.rpt}}",
        "puts CEDAR_DC_DONE",
        "exit 0",
    ]
    (work / "dc.tcl").write_text("\n".join(lines) + "\n")
    r = ctx.tools.run("synthesis", ["-f", str(work / "dc.tcl")], work, work / "dc.log", timeout, label="synthesis")
    if r.ok:
        log = Path(r.log).read_text(errors="replace")
        errs = re.findall(r"^CEDAR_ERROR.*", log, re.M)
        if not re.search(r"^CEDAR_DC_DONE", log, re.M) or errs:
            r.status, r.detail = "failed", (errs or ["DC did not complete"])[0]
    r.outputs = {"netlist": str(res / "netlist.v"), "sdc": str(sdc), "area_rpt": str(res / "area.rpt"),
                 "timing_rpt": str(res / "timing.rpt"), "power_rpt": str(res / "power.rpt"),
                 "cross_probing": str(res / "cross_probing.rpt"), "critical_path": str(res / "critical_path.rpt")}
    return r


def synth_metrics(ctx: FlowContext, r: StageResult) -> Dict[str, Metric]:
    stage = "post-synthesis"
    unit = ctx.time_unit
    out: Dict[str, Metric] = {}
    if not r.ok:
        for q in ("area", "delay", "slack"):
            out[q] = Metric.unavailable(q, stage, "dc", "failed", r.detail[:200])
        return out
    a = parse_dc_area(Path(r.outputs["area_rpt"]))
    t = parse_timing(Path(r.outputs["timing_rpt"]))
    out["area"] = Metric.measured("area", a, "um2", stage, "dc:report_area") if a is not None else \
        Metric.unavailable("area", stage, "dc:report_area", "missing", "Total cell area not found")
    out["delay"] = Metric.measured("delay", t["arrival"], unit, stage, "dc:report_timing") if t["arrival"] is not None else \
        Metric.unavailable("delay", stage, "dc:report_timing", "missing", "data arrival time not found (unconstrained?)")
    out["slack"] = Metric.measured("slack", t["slack"], unit, stage, "dc:report_timing") if t["slack"] is not None else \
        Metric.unavailable("slack", stage, "dc:report_timing", "missing", "slack not found")
    return out


def place_route(ctx: FlowContext, netlist: str, sdc: str, work: Path, timeout: Optional[int] = None) -> StageResult:
    work.mkdir(parents=True, exist_ok=True)
    pr = ctx.tech.data["place_route"]
    mmmc = [
        f"create_library_set -name libset -timing {tcl_list(ctx.libs())}",
        f"create_rc_corner -name rc -qx_tech_file {{{ctx.rc_tech()}}}",
        "create_delay_corner -name dc -library_set libset -rc_corner rc",
        f"create_constraint_mode -name func -sdc_files {{{sdc}}}",
        "create_analysis_view -name view -constraint_mode func -delay_corner dc",
        "set_analysis_view -setup {view} -hold {view}",
    ]
    (work / "mmmc.tcl").write_text("\n".join(mmmc) + "\n")
    m = pr.get("core_margin", 4.0)
    lines = [
        f"setMultiCpuUsage -localCpu {ctx.tools.threads}",
        f"setLibraryUnit -time 1{ctx.time_unit}",
        f"set init_verilog {{{netlist}}}",
        f"set init_lef_file {tcl_list(ctx.lefs())}",
        f"set init_top_cell {ctx.top}",
        "set init_design_netlisttype Verilog",
        f"set init_mmmc_file {{{work / 'mmmc.tcl'}}}",
        f"set init_pwr_net {pr.get('power_net', 'VDD')}",
        f"set init_gnd_net {pr.get('ground_net', 'VSS')}",
        "init_design",
    ]
    if ctx.hook("place_route", "post_init_hook"):
        lines.append(f"source {{{ctx.hook('place_route', 'post_init_hook')}}}")
    pw, gn = pr.get("power_net", "VDD"), pr.get("ground_net", "VSS")
    lo, hi = (pr.get("power_rail_layer_range") or ["M1", "M3"])[:2]
    lines += [
        "clearGlobalNets",
        f"globalNetConnect {pw} -type pgpin -pin {pw} -inst * -module {{}}",
        f"globalNetConnect {gn} -type pgpin -pin {gn} -inst * -module {{}}",
        f"floorPlan -site {pr['site']} -r 1.0 {pr.get('core_utilization', 0.6)} {m} {m} {m} {m}",
        f"sroute -connect {{ corePin }} -layerChangeRange {{ {lo} {hi} }} -corePinTarget {{ firstAfterRowEnd }} "
        f"-allowJogging 1 -nets {{ {pw} {gn} }} -allowLayerChange 1 -blockPin useLef",
        f"setMaxRouteLayer {pr.get('max_route_layer', 6)}",
        "place_design",
        f"setNanoRouteMode -routeTopRoutingLayer {pr.get('route_top_layer', 5)} "
        f"-routeBottomRoutingLayer {pr.get('route_bottom_layer', 2)} -routeWithViaInPin true",
    ]
    if ctx.hook("place_route", "pre_route_hook"):
        lines.append(f"source {{{ctx.hook('place_route', 'pre_route_hook')}}}")
    lines.append("routeDesign")
    if pr.get("filler_cells"):
        lines.append(f"addFiller -cell {{{' '.join(pr['filler_cells'])}}} -prefix FILLER_")
    lines += [
        "setExtractRCMode -engine postRoute",
        "extractRC",
        "rcOut -spef post_route.spef",
        "write_sdf post_route.sdf",
        "saveNetlist post_route.v",
        "setAnalysisMode -analysisType onChipVariation",
        "report_timing -max_paths 1 > post_route_timing.rpt",
        "puts CEDAR_INNOVUS_DONE",
        "exit",
    ]
    (work / "pnr.tcl").write_text("\n".join(lines) + "\n")
    r = ctx.tools.run("place_route", ["-no_gui", "-overwrite", "-files", str(work / "pnr.tcl")], work,
                      work / "innovus.log", timeout, stdin_text="", label="place_route")
    outs = {k: str(work / v) for k, v in (("netlist", "post_route.v"), ("spef", "post_route.spef"),
                                          ("sdf", "post_route.sdf"), ("timing_rpt", "post_route_timing.rpt"))}
    r.outputs = outs
    if r.ok:
        log = Path(r.log).read_text(errors="replace")
        missing = [k for k, v in outs.items() if k != "timing_rpt" and not Path(v).is_file()]
        if not re.search(r"^CEDAR_INNOVUS_DONE", log, re.M) or missing:
            r.status, r.detail = "failed", f"Innovus did not produce {missing or 'completion marker'}"
    return r


def activity_sim(ctx: FlowContext, netlist: str, sdf: str, testbench: str, tb_top: str, dut: str,
                 work: Path, timeout: Optional[int] = None) -> StageResult:
    """SDF-annotated gate-level simulation -> VCD -> SAIF."""
    work.mkdir(parents=True, exist_ok=True)
    period_ns = ctx.clocks[0]["period_ns_resolved"]
    args = ["-full64", "-sverilog", "-xprop=tmerge", "-override_timescale=1ns/1ps", "-top", tb_top,
            "+neg_tchk", "+sdfverbose", f"-sdf", f"max:{tb_top}.{dut}:{sdf}",
            f"+define+CYCLE_TIME={period_ns}", "+vcs+dumpvars+waves.vcd", "-o", "simv_gl"]
    args += ctx.sim_models() + [netlist, testbench]
    r = ctx.tools.run("simulation", args, work, work / "vcs_compile.log", timeout, label="activity_compile")
    if not r.ok:
        return r
    run_script = "./simv_gl -l sim.log"
    r2 = _shell(ctx, work, run_script, work / "vcs_run.log", timeout, "activity_sim", stage_tool="simulation")
    if not r2.ok:
        return r2
    if not (work / "waves.vcd").is_file():
        return StageResult("activity_sim", "failed", r.seconds + r2.seconds, r2.log, detail="no waves.vcd produced")
    r3 = ctx.tools.run("saif", ["-input", "waves.vcd", "-output", "waves.saif", "-instance", f"{tb_top}/{dut}"],
                       work, work / "vcd2saif.log", timeout, label="vcd2saif")
    if r3.ok and not (work / "waves.saif").is_file():
        r3.status, r3.detail = "failed", "vcd2saif produced no waves.saif"
    r3.seconds = round(r.seconds + r2.seconds + r3.seconds, 2)
    r3.stage = "activity"
    r3.outputs = {"saif": str(work / "waves.saif"), "vcd": str(work / "waves.vcd")}
    return r3


def _shell(ctx: FlowContext, work: Path, cmd: str, log: Path, timeout: Optional[int], label: str,
           stage_tool: str) -> StageResult:
    """Run a non-tool shell command (e.g. ./simv) inside the profile environment."""
    import subprocess
    import time
    tool = ctx.tools.tools.get(stage_tool, {})
    script = ctx.tools.prefix(tool.get("env_required") or []) + f"\nexec nice -n {ctx.tools.nice} {cmd}"
    t0 = time.monotonic()
    with open(log, "w") as fh:
        try:
            p = subprocess.run(["bash", "-c", script], cwd=str(work), stdout=fh, stderr=subprocess.STDOUT,
                               stdin=subprocess.DEVNULL, timeout=timeout or tool.get("timeout_s") or 1800,
                               start_new_session=True)
        except subprocess.TimeoutExpired:
            return StageResult(label, "timeout", round(time.monotonic() - t0, 2), str(log))
    return StageResult(label, "ok" if p.returncode == 0 else "failed", round(time.monotonic() - t0, 2), str(log),
                       p.returncode, "" if p.returncode == 0 else Path(log).read_text(errors="replace")[-500:])


def power_pt(ctx: FlowContext, netlist: str, spef: str, saif: str, sdc: str, tb_top: str, dut: str,
             work: Path, timeout: Optional[int] = None) -> StageResult:
    work.mkdir(parents=True, exist_ok=True)
    lines = [
        f"set dbs {tcl_list(ctx.dbs())}",
        "set_app_var target_library $dbs",
        "set_app_var link_library [concat * $dbs]",
        "set_app_var power_enable_analysis true",
        f"read_verilog {{{netlist}}}",
        f"current_design {ctx.top}",
        "if {![link_design]} { puts \"CEDAR_ERROR link failed\"; exit 2 }",
        f"read_sdc {{{sdc}}}",
        f"read_saif {{{saif}}} -strip_path {tb_top}/{dut}",
        f"read_parasitics -format spef {{{spef}}}",
        "update_power",
        "report_switching_activity > switching_activity.rpt",
        "report_power > power.rpt",
        "report_power -cell_power -nosplit > power_cells.rpt",
        "puts CEDAR_PT_DONE",
        "exit",
    ]
    (work / "pt.tcl").write_text("\n".join(lines) + "\n")
    r = ctx.tools.run("power", ["-f", str(work / "pt.tcl")], work, work / "pt.log", timeout, label="power")
    r.outputs = {"power_rpt": str(work / "power.rpt"), "activity_rpt": str(work / "switching_activity.rpt"),
                 "cell_power_rpt": str(work / "power_cells.rpt")}
    if r.ok:
        log = Path(r.log).read_text(errors="replace")
        if not re.search(r"^CEDAR_PT_DONE", log, re.M) or re.search(r"^CEDAR_ERROR", log, re.M):
            r.status, r.detail = "failed", "PrimeTime did not complete"
    return r


def power_metric(r: StageResult) -> Metric:
    stage, src = "post-route", "primetime:saif+spef"
    if not r.ok:
        return Metric.unavailable("power", stage, src, "failed", r.detail[:200])
    w = parse_pt_power(Path(r.outputs["power_rpt"]))
    if w is None:
        return Metric.unavailable("power", stage, src, "missing", "Total Power not found in report")
    return Metric.measured("power", w, "W", stage, src)


def conformal_lec(ctx: FlowContext, golden: Sequence[str], revised: Sequence[str], work: Path,
                  extra: Sequence[str] = (), timeout: Optional[int] = None) -> StageResult:
    """RTL-to-RTL equivalence (golden = original design). Fail-closed parsing."""
    work.mkdir(parents=True, exist_ok=True)
    fmt_g = "-systemverilog" if detect_hdl(golden) == "sverilog" else "-verilog"
    fmt_r = "-systemverilog" if detect_hdl(revised) == "sverilog" else "-verilog"
    tech_extra = (ctx.tech.data.get("equivalence") or {}).get("extra_commands") or []
    # Verilog command files carry the design's include dirs and defines so the
    # checked configuration is exactly the synthesized one.
    common = [f"+incdir+{d}" for d in ctx.include_dirs]
    common += [f"+define+{k}={v}" if v not in (None, "") else f"+define+{k}" for k, v in ctx.defines.items()]
    (work / "golden.f").write_text("\n".join(common + list(golden)) + "\n")
    (work / "revised.f").write_text("\n".join(common + list(revised)) + "\n")
    lines = [
        "set log file lec.log -replace",
        f"read design -file golden.f -golden {fmt_g}",
        f"read design -file revised.f -revised {fmt_r}",
        f"set root module {ctx.top} -golden",
        f"set root module {ctx.top} -revised",
        *tech_extra, *extra,
        "set system mode lec",
        "add compared points -all",
        "compare",
        "report compare data -summary > compare_summary.rpt",
        "report unmapped points -summary > unmapped.rpt",
        "report verification > verification.rpt",
        "exit -force",
    ]
    (work / "lec.do").write_text("\n".join(lines) + "\n")
    r = ctx.tools.run("equivalence", ["-nogui", "-dofile", str(work / "lec.do")], work, work / "conformal.log",
                      timeout, stdin_text="", label="equivalence")
    r.outputs = {"verification_rpt": str(work / "verification.rpt"), "log": str(work / "conformal.log")}
    return r


def parse_conformal(r: StageResult) -> Dict[str, object]:
    """Return {'status': passed|failed|error, 'detail':..., 'points':...}."""
    if r.status in ("unavailable", "timeout"):
        return {"status": "unavailable" if r.status == "unavailable" else "error", "detail": r.detail}
    log = Path(r.outputs.get("log", r.log)).read_text(errors="replace") if Path(r.outputs.get("log", r.log)).exists() else ""
    ver = Path(r.outputs["verification_rpt"])
    vtxt = ver.read_text(errors="replace") if ver.is_file() else ""
    m = re.search(r"Compare Results:\s+(\w+)", vtxt)
    inc = re.search(r"Incomplete verification:\s+(\d+)", vtxt)
    eq = re.search(r"^Equivalent\s+.*?(\d+)\s*$", log, re.M)
    neq = re.search(r"^Non-equivalent\s+.*?(\d+)\s*$", log, re.M)
    ab = re.search(r"^Abort\s+.*?(\d+)\s*$", log, re.M)
    points = int(eq.group(1)) if eq else 0
    if not m:
        return {"status": "error", "detail": "no 'Compare Results' in verification report", "points": points}
    if m.group(1) != "PASS":
        return {"status": "failed", "detail": f"Compare Results: {m.group(1)}"
                f"{'; non-equivalent ' + neq.group(1) if neq else ''}", "points": points}
    if inc and int(inc.group(1)) != 0:
        return {"status": "failed", "detail": f"incomplete verification items: {inc.group(1)}", "points": points}
    if (neq and int(neq.group(1)) > 0) or (ab and int(ab.group(1)) > 0):
        return {"status": "failed", "detail": "non-equivalent or aborted points", "points": points}
    if points == 0:
        return {"status": "error", "detail": "no compared points", "points": points}
    return {"status": "passed", "detail": f"Conformal PASS ({points} equivalent points)", "points": points}


def rtl_sim_check(ctx: FlowContext, design: Sequence[str], testbench: str, pass_marker: str, fail_marker: str,
                  work: Path, timeout: Optional[int] = None) -> Dict[str, object]:
    """Self-checking RTL simulation (explicitly selected verification mode)."""
    work.mkdir(parents=True, exist_ok=True)
    extra = [f"+incdir+{d}" for d in ctx.include_dirs]
    extra += [f"+define+{k}={v}" if v not in (None, "") else f"+define+{k}" for k, v in ctx.defines.items()]
    r = ctx.tools.run("simulation", ["-full64", "-sverilog", "+v2k", "-timescale=1ns/1ps", "-o", "simv_chk",
                                     *extra, *design, testbench], work, work / "vcs_check_compile.log", timeout,
                      label="sim_check_compile")
    if r.status == "unavailable":
        return {"status": "unavailable", "detail": r.detail}
    if r.status == "timeout":
        return {"status": "error", "detail": "simulation compile timed out"}
    if not r.ok:
        log = Path(r.log).read_text(errors="replace") if r.log and Path(r.log).is_file() else ""
        if re.search(r"licen[sc]e", log, re.I) and re.search(r"error|fail|unable|could not", log, re.I):
            return {"status": "error", "detail": "simulator license problem (not a candidate failure)"}
        return {"status": "failed", "detail": "candidate failed to compile with checking testbench"}
    r2 = _shell(ctx, work, "./simv_chk -l sim_check.log", work / "vcs_check_run.log", timeout, "sim_check", "simulation")
    if r2.status == "timeout":
        return {"status": "error", "detail": "checking simulation timed out"}
    txt = (work / "sim_check.log").read_text(errors="replace") if (work / "sim_check.log").is_file() else ""
    if fail_marker in txt:
        return {"status": "failed", "detail": f"testbench reported {fail_marker}"}
    if pass_marker in txt and r2.ok:
        return {"status": "passed", "detail": f"testbench printed {pass_marker}"}
    return {"status": "failed", "detail": f"pass marker {pass_marker!r} not found"}
