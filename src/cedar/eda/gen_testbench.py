"""Generate an *activity-only* random-stimulus testbench (power analysis).

The generated testbench applies random values to every non-clock, non-reset
input each cycle after holding the declared resets active for four cycles. It
never checks outputs and is therefore never accepted as correctness evidence
(see :mod:`cedar.verification`). Ports are read from the CIRCT frontend's
``hw.module`` signature, so any synthesizable Verilog/SystemVerilog the
frontend accepts is supported.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import List, Sequence, Tuple

from ..egraph import pipeline
from ..toolchain import Toolchain


def ports(tc: Toolchain, rtl: Sequence[str], top: str, work: Path, include_dirs: Sequence[str] = (),
          defines=None) -> List[Tuple[str, str, int]]:
    work.mkdir(parents=True, exist_ok=True)
    mlir = work / "ports.mlir"
    pipeline.frontend(tc, rtl, top, mlir, work, include_dirs, defines, flatten=False)
    m = re.search(rf"hw\.module\s+@{re.escape(top)}\((.*?)\)\s*(?:attributes|\{{)", mlir.read_text(), re.S)
    if not m:
        raise RuntimeError(f"cannot find hw.module @{top}")
    out = []
    for d, name, w in re.findall(r"\b(in|out|inout)\s+%?(\"?[\w$]+\"?)\s*:\s*(?:i(\d+)|!seq\.clock)", m.group(1)):
        out.append((d, name.strip('"'), int(w) if w else 1))
    return out


def generate_activity_testbench(tc: Toolchain, rtl: Sequence[str], top: str, out: Path, clocks: Sequence[dict],
                                resets: Sequence[dict], cycles: int = 1000, seed: int = 1,
                                include_dirs: Sequence[str] = (), defines=None) -> Path:
    ps = ports(tc, rtl, top, out.parent / "tbgen", include_dirs, defines)
    clk_ports = {c.get("port") for c in clocks if c.get("port")}
    rst = {r["port"]: r for r in resets}
    decl, conns, drive, init = [], [], [], []
    for d, name, w in ps:
        rng = f"[{w - 1}:0] " if w > 1 else ""
        if d == "in":
            decl.append(f"  reg {rng}{name};")
            if name in clk_ports:
                init.append(f"    {name} = 1'b0;")
            elif name in rst:
                act = "1'b1" if rst[name].get("active", "high") == "high" else "1'b0"
                init.append(f"    {name} = {act};")
            else:
                init.append(f"    {name} = 0;")
                drive.append(f"      {name} = $random(seed);")
        else:
            decl.append(f"  wire {rng}{name};")
        conns.append(f".{name}({name})")
    clk_lines = [f"  always #(`CYCLE_TIME / 2.0) {c} = ~{c};" for c in clk_ports]
    lo, hi = "1'b0", "1'b1"
    deassert = ["    %s = %s;" % (p, lo if r.get("active", "high") == "high" else hi) for p, r in rst.items()]
    tb = "\n".join([
        "// Generated by Cedar: ACTIVITY-ONLY random stimulus (no output checking).",
        "`timescale 1ns/1ps", "`ifndef CYCLE_TIME", "`define CYCLE_TIME 1.0", "`endif",
        "module Top;", "  integer i, seed;", *decl,
        f"  {top} DUT ({', '.join(conns)});", *clk_lines,
        "  initial begin", f"    seed = {int(seed)};", *init,
        "    repeat (4) #(`CYCLE_TIME);" if not clk_ports else "    repeat (4) @(negedge " + sorted(clk_ports)[0] + ");",
        *deassert,
        f"    for (i = 0; i < {int(cycles)}; i = i + 1) begin",
        ("      @(negedge " + sorted(clk_ports)[0] + ");") if clk_ports else "      #(`CYCLE_TIME);",
        *drive, "    end", "    #(`CYCLE_TIME);", "    $finish;", "  end", "endmodule", ""])
    out.write_text(tb)
    return out
