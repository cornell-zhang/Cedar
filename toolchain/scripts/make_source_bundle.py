#!/usr/bin/env python3
# SPDX-License-Identifier: Apache-2.0
"""Create a release source bundle: Cedar + every pinned dependency source.

The bundle makes the toolchain's *source availability* independent of any
private repository or of upstream hosting:

    cedar-src-<version>/
      cedar/                 git archive of the Cedar commit (incl. third_party/)
      sources/circt/         CIRCT at the pinned revision, with llvm/ inside
      sources/slang/  sources/fmt/  sources/egglog/
      vendor/egglog/  vendor/extraction-gym/   `cargo vendor` crate sources
      BUNDLE.json            lockfile copy, revisions, per-tree SHA-256, build recipe

Build from an unpacked bundle without network access to source hosts:

    CEDAR_SOURCES_DIR=$PWD/sources CARGO_OFFLINE=1 \\
        cedar/toolchain/build/build-native.sh

A *fully* offline build additionally needs the build tools themselves (C++
compiler, cmake, ninja, lld, Rust toolchain); those are not in the bundle.

Usage: make_source_bundle.py --out DIR [--rev HEAD] [--cargo CARGO] [--no-archive]
Requires git and cargo; fetches pinned sources over anonymous HTTPS.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import os
import shutil
import subprocess
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def run(cmd, cwd=None, **kw):
    print("+", " ".join(str(c) for c in cmd), flush=True)
    return subprocess.run([str(c) for c in cmd], cwd=cwd, check=True, **kw)


def fetch(dest: Path, url: str, sha: str) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    run(["git", "init", "-q"], cwd=dest)
    run(["git", "remote", "add", "origin", url], cwd=dest)
    run(["git", "-c", "protocol.version=2", "fetch", "-q", "--depth", "1", "origin", sha], cwd=dest)
    run(["git", "checkout", "-q", "FETCH_HEAD"], cwd=dest)
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=dest, capture_output=True, text=True).stdout.strip()
    if head != sha:
        raise SystemExit(f"{url}: fetched {head}, expected {sha}")
    shutil.rmtree(dest / ".git")


def tree_sha(path: Path) -> str:
    h = hashlib.sha256()
    for p in sorted(path.rglob("*")):
        if p.is_file() and not p.is_symlink():
            h.update(str(p.relative_to(path)).encode())
            h.update(hashlib.sha256(p.read_bytes()).digest())
    return h.hexdigest()


def cargo_vendor(cargo: str, crate_dir: Path, vendor_dir: Path) -> None:
    """Vendor crates and write <crate>/.cargo/config.toml pointing at them."""
    out = subprocess.run([cargo, "vendor", "--locked", "--versioned-dirs", str(vendor_dir)], cwd=crate_dir,
                         check=True, capture_output=True, text=True).stdout
    rel = os.path.relpath(vendor_dir, crate_dir)
    cfg = out.replace(f'directory = "{vendor_dir}"', f'directory = "{rel}"')
    (crate_dir / ".cargo").mkdir(exist_ok=True)
    (crate_dir / ".cargo" / "config.toml").write_text(
        "# Generated by make_source_bundle.py: build from vendored crates.\n" + cfg)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--rev", default="HEAD", help="Cedar git revision to bundle")
    ap.add_argument("--cargo", default=shutil.which("cargo") or "cargo")
    ap.add_argument("--no-archive", action="store_true", help="leave the bundle unpacked only")
    args = ap.parse_args()
    lock = json.loads((ROOT / "toolchain" / "sources.lock.json").read_text())
    rev = subprocess.run(["git", "rev-parse", args.rev], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    name = f"cedar-src-{lock['toolchain_version']}"
    top = args.out.resolve() / name
    if top.exists():
        shutil.rmtree(top)
    top.mkdir(parents=True)

    # 1. Cedar itself (committed content only; never the working tree).
    data = subprocess.run(["git", "archive", "--format=tar", rev], cwd=ROOT, check=True, capture_output=True).stdout
    with tarfile.open(fileobj=io.BytesIO(data)) as tf:
        kw = {"filter": "data"} if hasattr(tarfile, "data_filter") else {}
        tf.extractall(top / "cedar", **kw)

    # 2. Pinned git sources.
    comps = lock["components"]
    src = top / "sources"
    fetch(src / "circt", comps["circt"]["url"], comps["circt"]["revision"])
    shutil.rmtree(src / "circt" / "llvm", ignore_errors=True)
    fetch(src / "circt" / "llvm", comps["llvm"]["url"], comps["llvm"]["revision"])
    for c in ("slang", "fmt", "egglog"):
        fetch(src / c, comps[c]["url"], comps[c]["revision"])

    # 3. Rust crates.
    cargo_vendor(args.cargo, src / "egglog", top / "vendor" / "egglog")
    cargo_vendor(args.cargo, top / "cedar" / "third_party" / "extraction-gym", top / "vendor" / "extraction-gym")

    manifest = {
        "schema": "cedar-source-bundle/1",
        "cedar_revision": rev,
        "lock": lock,
        "trees": {p: tree_sha(top / p) for p in ("cedar", "sources/circt", "sources/slang", "sources/fmt",
                                                  "sources/egglog", "vendor/egglog", "vendor/extraction-gym")},
        "build": "CEDAR_SOURCES_DIR=$PWD/sources CARGO_OFFLINE=1 cedar/toolchain/build/build-native.sh",
        "not_included": "compilers, cmake, ninja, lld, Rust toolchain, Python build tools",
    }
    (top / "BUNDLE.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"bundle tree: {top}")
    if not args.no_archive:
        arc = args.out.resolve() / f"{name}.tar.gz"
        run(["tar", "-C", str(args.out.resolve()), "-czf", str(arc), name])
        print(f"bundle archive: {arc} ({arc.stat().st_size / 1e6:.0f} MB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
